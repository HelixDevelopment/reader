#!/usr/bin/env python3
"""HRD-070 rule enumerator (round 5).

Derives the rule list MECHANICALLY from the production source: every
if / else / case / switch / for / default line inside the functions under test.
Each is looked up in rulemap.tsv (checked in) and must map to mutants that the
mutation log shows KILLED, or to a justified EQUIV / UNREACHABLE entry whose
mutant the log shows SURVIVED (expected).  Fails (exit 1) on: an unmapped
branch, a mapped branch whose mutant is not in the log or has the wrong outcome,
a map row that matches no branch (stale).  Emits RULES.md.
usage: enumerate_rules.py <repo-root> <mutation.log> <rulemap.tsv> <out RULES.md>
"""
import re, sys
root, logp, mapp, outp = sys.argv[1:5]
FUNCS = {
 'core/pkg/lcp/license.go': ['Parse', 'parseTime'],
 'core/pkg/lcp/lsd.go': ['ParseStatusDocument', 'parseRels', 'parseStatusTime'],
 'server/internal/kosync/service.go': ['Register', 'Authenticate', 'PutProgress', 'GetProgress'],
 'server/internal/opds/opds12.go': None, 'server/internal/opds/opds20.go': None,
 'server/internal/opds/detail.go': None,
}
PAT = re.compile(r'^\s*(if |\} else|case |for |switch |default:)')
branches = []  # (file, func, line, text, occ)
for f, fn in FUNCS.items():
    cur = None; seen = {}
    for i, l in enumerate(open(f"{root}/{f}").read().split('\n'), 1):
        m = re.match(r'^func (?:\([^)]*\) )?(\w+)', l)
        if m: cur = m.group(1)
        if cur and (fn is None or cur in fn) and PAT.match(l):
            t = l.strip(); k = (f, cur, t); seen[k] = seen.get(k, 0) + 1
            branches.append((f, cur, i, t, seen[k]))
log = {}
for l in open(logp):
    m = re.match(r'MUTANT (\S+): (.*)', l)
    if m: log[m.group(1)] = m.group(2).strip()
rows = {}
for l in open(mapp):
    if l.startswith('#') or not l.strip(): continue
    f, fn, occ, text, disp, why = l.rstrip('\n').split('\t')
    rows[(f, fn, text, int(occ))] = (disp, why)
errs = []; used = set(); out = []
for f, fn, ln, t, occ in branches:
    key = (f, fn, t, occ)
    if key not in rows: errs.append(f"UNMAPPED {f}:{ln} {fn}: {t}"); continue
    used.add(key); disp, why = rows[key]
    kind = disp.split(':')[0]
    ms = disp.split(':', 1)[1].split(',') if ':' in disp else []
    status = []
    for mu in ms:
        r = log.get(mu)
        if r is None: errs.append(f"NO-LOG {mu} (for {f}:{ln})"); status.append(f"{mu}=?"); continue
        want = 'SURVIVED' if kind in ('EQUIV', 'UNREACHABLE') else 'KILLED'
        if not r.startswith(want) or 'BAD' in r: errs.append(f"WRONG {mu}: log says '{r}' want {want} ({f}:{ln})")
        status.append(f"{mu}={r.split()[0]}")
    if kind in ('EQUIV', 'UNREACHABLE') and not ms: errs.append(f"NEEDS-MUTANT {f}:{ln}")
    if kind == 'KILL' and not ms: errs.append(f"EMPTY {f}:{ln}")
    out.append((f, ln, fn, t, kind, ', '.join(status), why))
for k in rows:
    if k not in used: errs.append(f"STALE map row {k}")
with open(outp, 'w') as o:
    o.write("# HRD-070 rule table (generated by enumerate_rules.py from production source)\n\n")
    o.write(f"{len(branches)} branch lines enumerated; {len(errs)} problems.\n\n")
    o.write("| source | function | branch (text) | disposition | mutant(s) = outcome | oracle / why |\n|---|---|---|---|---|---|\n")
    for f, ln, fn, t, kind, st, why in out:
        o.write(f"| {f}:{ln} | {fn} | `{t.replace('|','\\|')}` | {kind} | {st} | {why} |\n")
if errs:
    print('\n'.join(errs)); sys.exit(1)
print(f"OK: {len(branches)} branches, all mapped and outcomes match the mutation log")
