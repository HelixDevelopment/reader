#!/usr/bin/env bash
# test_build_evidence_manifest.sh - mutation tests for build_evidence_manifest.sh --check
# (HRD-051 review fixes). Every case runs in a scratch git repo; the real tree is never touched.
# Covers: vacuous passes (rows==0, with_evidence==0, empty manifest), blank-cell parsing in each of
# the 12 columns (must name the column), volatile (untracked/modified) evidence, snapshot provenance.
# Usage: scripts/gates/test_build_evidence_manifest.sh      exit 0 = every case behaved
set -u
here="$(cd "$(dirname "$0")" && pwd)"; tool="$here/build_evidence_manifest.sh"
base="$(mktemp -d -t ledfix_XXXXXX)"; trap 'rm -rf "$base"' EXIT
pass=0; fail=0
ok()  { pass=$((pass+1)); echo "PASS $1"; }
bad() { fail=$((fail+1)); echo "FAIL $1"; }
HDR=$'id\tcapability\tbluff_type\tseverity\tclaim_status\tlayer\tsource\tevidence_path\tevidence_sha256\tproducer\tlast_verified\tnotes'
COLS=(id capability bluff_type severity claim_status layer source evidence_path evidence_sha256 producer last_verified notes)
SNAP=evidence/campaign-2026-11-23/gap-fix/ledger-snapshots

mk() { # mk <dir>: tracked good tree with one evidence row and one none row
  local d="$1"; mkdir -p "$d/docs/evidence" "$d/evidence"
  printf 'l1\nl2\nl3\n' > "$d/README.md"; echo 'ok 1' > "$d/evidence/a.log"
  { echo "$HDR"
    printf 'LED-001\tcap one\tdoc-vs-code-drift\thigh\tVERIFIED\tSOURCE\tREADME.md:2\tevidence/a.log\tnone\tcmd a\t2026-11-23\tnote a\n'
    printf 'LED-002\tcap two\tdoc-vs-code-drift\tlow\tBUILT\tSOURCE\tREADME.md:3\tnone\tnone\tcmd b\t2026-11-23\tnote b\n'
  } > "$d/docs/claim_reality_ledger.tsv"
  ( cd "$d" && git init -q . && git add -A && git -c user.email=t@t -c user.name=t commit -qm i ) >/dev/null 2>&1
  "$tool" --root "$d" >/dev/null 2>&1
}
run() { "$tool" --check --root "$1" 2>&1; }

# 0 baseline
d="$base/ok"; mk "$d"; out="$(run "$d")"; rc=$?
[ $rc = 0 ] && ok "baseline good tree accepted" || { bad "baseline rejected: $out"; }

# 3 vacuous: zero rows
d="$base/zero"; mk "$d"; echo "$HDR" > "$d/docs/claim_reality_ledger.tsv"
printf '# gate evidence manifest (§11.4.262) - generated by scripts/gates/build_evidence_manifest.sh from docs/claim_reality_ledger.tsv; do not hand-edit\n# columns: gate_id<TAB>layer<TAB>evidence-path<TAB>sha256\n' > "$d/docs/evidence/gate_evidence_manifest.tsv"
out="$(run "$d")"; rc=$?; { [ $rc != 0 ] && echo "$out" | grep -q 'VACUOUS'; } && ok "rows==0 fails VACUOUS" || bad "rows==0 accepted (rc=$rc): $out"

# 3 vacuous: with_evidence==0
d="$base/noev"; mk "$d"
{ echo "$HDR"; printf 'LED-002\tcap two\tdoc-vs-code-drift\tlow\tBUILT\tSOURCE\tREADME.md:3\tnone\tnone\tcmd b\t2026-11-23\tnote b\n'; } > "$d/docs/claim_reality_ledger.tsv"
"$tool" --root "$d" >/dev/null 2>&1
out="$(run "$d")"; rc=$?; { [ $rc != 0 ] && echo "$out" | grep -q 'VACUOUS'; } && ok "with_evidence==0 fails VACUOUS" || bad "with_evidence==0 accepted (rc=$rc): $out"

# 3 vacuous: manifest has zero data rows while ledger has evidence rows
d="$base/emptyman"; mk "$d"
grep '^#' "$d/docs/evidence/gate_evidence_manifest.tsv" | grep -v 'producer:' > "$d/docs/evidence/m.tmp"; mv "$d/docs/evidence/m.tmp" "$d/docs/evidence/gate_evidence_manifest.tsv"
out="$(run "$d")"; rc=$?; { [ $rc != 0 ] && echo "$out" | grep -q 'VACUOUS'; } && ok "empty manifest vs evidence rows fails VACUOUS" || bad "empty manifest accepted (rc=$rc): $out"

# 4 blank cell in each column (ids kept so the row is identifiable)
for i in $(seq 0 11); do
  d="$base/blank$i"; mk "$d"
  awk -F'\t' -v OFS='\t' -v c=$((i+1)) 'NR==2{$c=""} {print}' "$d/docs/claim_reality_ledger.tsv" > "$d/l.tmp" && mv "$d/l.tmp" "$d/docs/claim_reality_ledger.tsv"
  out="$(run "$d")"; rc=$?
  if [ $rc != 0 ] && echo "$out" | grep -q "BLANK_CELL.*'${COLS[$i]}'"; then ok "blank ${COLS[$i]} reported by name"
  else bad "blank ${COLS[$i]} not reported by name (rc=$rc): $(echo "$out" | head -3 | tr '\n' '|')"; fi
done
# wrong column count
d="$base/ncol"; mk "$d"; printf 'LED-003\tonly\tthree\n' >> "$d/docs/claim_reality_ledger.tsv"
out="$(run "$d")"; rc=$?; { [ $rc != 0 ] && echo "$out" | grep -q 'COLUMN_COUNT'; } && ok "short row fails COLUMN_COUNT" || bad "short row accepted (rc=$rc)"

# 1 volatile evidence: untracked file outside snapshots
d="$base/volatile"; mk "$d"; mkdir -p "$d/evidence/clients"; echo '{"x":1}' > "$d/evidence/clients/v.json"
awk -F'\t' -v OFS='\t' 'NR==2{$8="evidence/clients/v.json"} {print}' "$d/docs/claim_reality_ledger.tsv" > "$d/l.tmp" && mv "$d/l.tmp" "$d/docs/claim_reality_ledger.tsv"
"$tool" --root "$d" >/dev/null 2>&1; out="$(run "$d")"; rc=$?
{ [ $rc != 0 ] && echo "$out" | grep -q 'VOLATILE_EVIDENCE'; } && ok "untracked evidence outside snapshots fails VOLATILE_EVIDENCE" || bad "volatile accepted (rc=$rc): $out"
# tracked but modified
d="$base/modified"; mk "$d"; echo 'changed' >> "$d/evidence/a.log"; "$tool" --root "$d" >/dev/null 2>&1; out="$(run "$d")"; rc=$?
{ [ $rc != 0 ] && echo "$out" | grep -q 'VOLATILE_EVIDENCE'; } && ok "modified-tracked evidence fails VOLATILE_EVIDENCE" || bad "modified accepted (rc=$rc): $out"
# snapshot without provenance
d="$base/snapnoprov"; mk "$d"; mkdir -p "$d/$SNAP"; echo 'frozen' > "$d/$SNAP/s.txt"
awk -F'\t' -v OFS='\t' -v p="$SNAP/s.txt" 'NR==2{$8=p} {print}' "$d/docs/claim_reality_ledger.tsv" > "$d/l.tmp" && mv "$d/l.tmp" "$d/docs/claim_reality_ledger.tsv"
"$tool" --root "$d" >/dev/null 2>&1; out="$(run "$d")"; rc=$?
{ [ $rc != 0 ] && echo "$out" | grep -q 'SNAPSHOT_PROVENANCE'; } && ok "snapshot without provenance fails" || bad "snapshot w/o provenance accepted (rc=$rc): $out"
# snapshot with provenance accepted; then tampered snapshot rejected
sha="$(sha256sum "$d/$SNAP/s.txt" | cut -d' ' -f1)"
printf 'snapshot\tsource_path\tcaptured_at\tsnapshotted_at\tsha256\ns.txt\tREADME.md\t2026-11-23T00:00:00Z\t2026-11-23T00:00:01Z\t%s\n' "$sha" > "$d/$SNAP/PROVENANCE.tsv"
"$tool" --root "$d" >/dev/null 2>&1; out="$(run "$d")"; rc=$?
[ $rc = 0 ] && ok "snapshot with matching provenance accepted" || bad "good snapshot rejected: $out"
echo 'tamper' >> "$d/$SNAP/s.txt"; out="$(run "$d")"; rc=$?
[ $rc != 0 ] && ok "tampered snapshot rejected" || bad "tampered snapshot accepted"

# ---- review round 2 cases ----
setev() { # setev <dir> <evidence_path>  (row 2 only)
  awk -F'\t' -v OFS='\t' -v p="$2" 'NR==2{$8=p} {print}' "$1/docs/claim_reality_ledger.tsv" > "$1/l.tmp" && mv "$1/l.tmp" "$1/docs/claim_reality_ledger.tsv"; }
prov() { # prov <dir> <name> <source_path> <captured> <snapshotted> <sha>
  [ -f "$1/$SNAP/PROVENANCE.tsv" ] || printf 'snapshot\tsource_path\tcaptured_at\tsnapshotted_at\tsha256\n' > "$1/$SNAP/PROVENANCE.tsv"
  printf '%s\t%s\t%s\t%s\t%s\n' "$2" "$3" "$4" "$5" "$6" >> "$1/$SNAP/PROVENANCE.tsv"; }
expect() { # expect <label> <dir> <token>  : check must fail naming token
  local out rc; out="$(run "$2")"; rc=$?
  if [ $rc != 0 ] && echo "$out" | grep -q "$3"; then ok "$1"; else bad "$1 (rc=$rc): $(echo "$out" | head -3 | tr '\n' '|')"; fi; }
# 1 traversal
d="$base/trav"; mk "$d"; mkdir -p "$d/$SNAP"; echo out > "$d/outside.txt"; setev "$d" "$SNAP/../../../../outside.txt"
prov "$d" "../../../../outside.txt" README.md 2026-11-23T00:00:00Z 2026-11-23T00:00:01Z "$(sha256sum "$d/outside.txt" | cut -d' ' -f1)"
"$tool" --root "$d" >/dev/null 2>&1; expect "path traversal rejected" "$d" PATH_ESCAPE
d="$base/abs"; mk "$d"; setev "$d" "/etc/hostname"; expect "absolute evidence path rejected" "$d" PATH_ESCAPE
# 2 authenticity
snapmk() { d="$1"; mk "$d"; mkdir -p "$d/$SNAP"; echo frozen > "$d/$SNAP/s.txt"; setev "$d" "$SNAP/s.txt"; sha="$(sha256sum "$d/$SNAP/s.txt" | cut -d' ' -f1)"; }
snapmk "$base/forged"; prov "$d" s.txt evidence/nonexistent.json 2099-01-01T00:00:00Z 2099-01-02T00:00:00Z "$sha"; "$tool" --root "$d" >/dev/null 2>&1
expect "forged nonexistent source + 2099 date fails" "$d" SNAPSHOT_AUTHENTICITY
snapmk "$base/future"; prov "$d" s.txt README.md 2099-01-01T00:00:00Z 2099-01-02T00:00:00Z "$sha"; "$tool" --root "$d" >/dev/null 2>&1; expect "future captured_at fails" "$d" SNAPSHOT_AUTHENTICITY
snapmk "$base/order"; prov "$d" s.txt README.md 2026-11-23T10:00:00Z 2026-11-23T09:00:00Z "$sha"; "$tool" --root "$d" >/dev/null 2>&1; expect "captured after snapshotted fails" "$d" SNAPSHOT_AUTHENTICITY
snapmk "$base/gone"; prov "$d" s.txt "gone:" 2026-11-23T09:00:00Z 2026-11-23T10:00:00Z "$sha"; "$tool" --root "$d" >/dev/null 2>&1; expect "gone without reason fails" "$d" SNAPSHOT_AUTHENTICITY
snapmk "$base/gone2"; prov "$d" s.txt "gone:deleted by cleanup" 2026-11-23T09:00:00Z 2026-11-23T10:00:00Z "$sha"; "$tool" --root "$d" >/dev/null 2>&1
out="$(run "$d")"; rc=$?; [ $rc = 0 ] && ok "gone with reason accepted" || bad "gone+reason rejected: $out"
snapmk "$base/stale"; printf "different\nx\ny\n" > "$d/README.md"; prov "$d" s.txt README.md 2026-11-23T09:00:00Z 2026-11-23T10:00:00Z "$sha"; (cd "$d" && git add -A && git -c user.email=t@t -c user.name=t commit -qm r) >/dev/null 2>&1; "$tool" --root "$d" >/dev/null 2>&1
out="$(run "$d")"; rc=$?; { echo "$out" | grep -q 'WARN STALE_SNAPSHOT'; } && ok "source sha drift reported as WARN STALE_SNAPSHOT" || bad "no stale warning (rc=$rc): $out"
# 3 staged modification / non-git
d="$base/staged"; mk "$d"; echo more >> "$d/evidence/a.log"; (cd "$d" && git add evidence/a.log); "$tool" --root "$d" >/dev/null 2>&1; expect "staged modification fails" "$d" VOLATILE_EVIDENCE
d="$base/nogit"; mk "$d"; rm -rf "$d/.git"; "$tool" --root "$d" >/dev/null 2>&1; expect "non-git root fails closed for non-snapshot evidence" "$d" NOT_GIT
# 4 symlink
d="$base/sym"; mk "$d"; ln -s a.log "$d/evidence/link.log"; (cd "$d" && git add -A && git -c user.email=t@t -c user.name=t commit -qm l) >/dev/null 2>&1; setev "$d" evidence/link.log; "$tool" --root "$d" >/dev/null 2>&1; expect "symlink evidence rejected" "$d" SYMLINK_EVIDENCE
# 5 duplicate ids
d="$base/dup"; mk "$d"; sed -n 3p "$d/docs/claim_reality_ledger.tsv" | sed 's/^LED-002/LED-001/' >> "$d/docs/claim_reality_ledger.tsv"; "$tool" --root "$d" >/dev/null 2>&1; expect "duplicate id rejected" "$d" DUPLICATE_ID
# 7 CRLF
d="$base/crlf"; mk "$d"; sed -i 's/$/\r/' "$d/docs/claim_reality_ledger.tsv"; expect "CRLF reported explicitly" "$d" 'CRLF line endings'

echo "== $pass passed, $fail failed"; [ $fail = 0 ]
