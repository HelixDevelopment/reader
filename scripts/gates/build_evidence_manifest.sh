#!/usr/bin/env bash
# build_evidence_manifest.sh - builds the §11.4.262 gate-evidence manifest from the
# §11.4.266 claim-vs-reality ledger (HRD-051).
#
# Inputs : docs/claim_reality_ledger.tsv  (header-bearing TSV; columns: id, capability,
#          bluff_type, severity, claim_status, layer, source, evidence_path,
#          evidence_sha256, producer, last_verified, notes)
# Outputs: docs/evidence/gate_evidence_manifest.tsv  (gate_id<TAB>layer<TAB>path<TAB>sha256,
#          one row per ledger row whose evidence_path is a real file; the producer command is
#          recorded as a '#' comment above each row) and the evidence_sha256 column of the ledger.
# Modes  : (default) rewrite both; --check  read-only consistency check (exit 1 on any defect):
#   - claim_status in BUILT|VERIFIED|PARTIAL|NOT_IMPLEMENTED|BLOCKED
#   - VERIFIED/PARTIAL/BLOCKED rows MUST carry an existing non-empty evidence file whose sha256
#     matches the ledger and the manifest; BUILT/NOT_IMPLEMENTED rows with evidence 'none' must say sha 'none'
#   - source is file:line with the file existing and the line within it
#   - the manifest has exactly the rows the ledger implies
#   - NOT VACUOUS: rows>0, with_evidence>0, and a manifest with data rows (VACUOUS)
#   - every row has exactly 12 columns and no blank cell; the column is named (COLUMN_COUNT, BLANK_CELL).
#     Parsing is awk-based with a non-whitespace separator so empty cells are preserved (an
#     IFS=tab `read` collapses adjacent tabs and silently shifts every later column).
#   - FROZEN EVIDENCE RULE (VOLATILE_EVIDENCE / SNAPSHOT_PROVENANCE): ledger rows cite only frozen
#     evidence = a file git tracks AND has not modified, OR a file under
#     evidence/campaign-2026-11-23/gap-fix/ledger-snapshots/ whose sha256 matches its row in that
#     directory's PROVENANCE.tsv. Untracked or modified evidence trees (evidence/clients/**, client
#     status manifests, ...) are rewritten by other work and made the gate flaky; snapshot them first.
#   - PATH_ESCAPE (evidence path absolute or containing '..'), SYMLINK_EVIDENCE (path or a parent is a
#     symlink), DUPLICATE_ID, CRLF line endings, NOT_GIT (non-git root: only snapshot evidence allowed;
#     fail-closed), staged changes count as modified (git diff HEAD)
#   - SNAPSHOT_AUTHENTICITY: every PROVENANCE.tsv row has a plain file name (no '/' or '..'), a
#     source_path that exists or is 'gone:<reason>', ISO captured_at/snapshotted_at not in the future and
#     captured_at <= snapshotted_at; a still-present source whose sha differs from the snapshot prints
#     'WARN STALE_SNAPSHOT' (not a failure: snapshots are point-in-time)
#   - CONTROL_BYTE: any C0 control byte other than TAB/LF/CR (or DEL) in the ledger or in a PROVENANCE.tsv is
#     refused (a 0x1F inside a cell would desync the single-pass cell join below and let a row read as
#     something else than what the constitution gates read: false green, review C18). CR has its own CRLF check.
#   - SOURCE_ESCAPE (source file absolute or with a '..' component, or resolving outside the root), source
#     line 0, BAD_DATE (last_verified must be a real YYYY-MM-DD not in the future)
#   - BAD_ID (id must be [A-Z]+-[0-9]+), byte-exact header (no extra column), git pathspecs are literal
#     (a '?' or '*' in an evidence path never matches another file), and tracked evidence hidden with
#     assume-unchanged / skip-worktree is VOLATILE_EVIDENCE
#   - snapshot files and PROVENANCE.tsv must be git-tracked and unmodified on a git root (SNAPSHOT_UNTRACKED /
#     SNAPSHOT_MODIFIED), so 'frozen' is not self-attested
# Usage  : scripts/gates/build_evidence_manifest.sh [--check] [--root DIR]
set -u
mode=build; root="$(cd "$(dirname "$0")/../.." && pwd)"
while [ $# -gt 0 ]; do case "$1" in
  --check) mode=check; shift;; --root) root="$2"; shift 2;; *) echo "unknown arg $1" >&2; exit 2;; esac; done
led="$root/docs/claim_reality_ledger.tsv"; man="$root/docs/evidence/gate_evidence_manifest.tsv"
[ -f "$led" ] || { echo "ledger missing: $led" >&2; exit 2; }
fail=0; rows=0; withev=0; seen=""
SNAP=evidence/campaign-2026-11-23/gap-fix/ledger-snapshots
COLS="id capability bluff_type severity claim_status layer source evidence_path evidence_sha256 producer last_verified notes"
newled="$(mktemp)"; newman="$(mktemp)"; parsed="$(mktemp)"; trap 'rm -f "$newled" "$newman" "$parsed"' EXIT
isgit=0; git -C "$root" rev-parse --git-dir >/dev/null 2>&1 && isgit=1
printf '# gate evidence manifest (§11.4.262) - generated by scripts/gates/build_evidence_manifest.sh from docs/claim_reality_ledger.tsv; do not hand-edit\n# columns: gate_id<TAB>layer<TAB>evidence-path<TAB>sha256\n' > "$newman"
# awk parse: FS=tab keeps empty cells; output joined with \037 (non-whitespace, so bash read keeps empties).
# Emits "HDR\037..." / "ROW\037lineno\037c1..c12" / "BADCOUNT\037lineno\037NF" lines.
awk -F'\t' 'BEGIN{OFS="\037"} NR==1{printf "HDR"; for(i=1;i<=NF;i++) printf "\037%s",$i; printf "\n"; next}
  /^[[:space:]]*$/{next}
  NF!=12{print "BADCOUNT",NR,NF; next}
  {printf "ROW\037%d",NR; for(i=1;i<=12;i++) printf "\037%s",$i; printf "\n"}' "$led" > "$parsed"
if grep -q $'\r' "$led"; then echo "FAIL CRLF line endings in $led (lines: $(grep -n $'\r' "$led" | cut -d: -f1 | head -5 | tr '\n' ' ')) - convert to LF"; fail=1; fi
CTL='[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]'
ctl_check() { # ctl_check <file> <label>: refuse C0 controls except TAB, LF, CR (CR has its own check) and DEL
  [ -f "$1" ] || return 0
  if LC_ALL=C grep -naP "$CTL" "$1" >/dev/null 2>&1; then
    echo "FAIL CONTROL_BYTE $2 contains a control byte (lines: $(LC_ALL=C grep -naP "$CTL" "$1" | cut -d: -f1 | head -5 | tr '\n' ' ')) - refused"; fail=1
  fi
}
ctl_check "$led" "ledger"; ctl_check "$root/$SNAP/PROVENANCE.tsv" "PROVENANCE.tsv"
hidden_flag() { # hidden_flag <path>: prints the 'git ls-files -v' tag when it is not H (assume-unchanged h/S skip-worktree/...)
  local t; t="$(git --literal-pathspecs -C "$root" ls-files -v -- "$1" 2>/dev/null | head -1 | cut -c1)"; [ -n "$t" ] && [ "$t" != H ] && echo "$t"; }
iso_ok() { date -u -d "$1" +%s >/dev/null 2>&1 && [[ "$1" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9:]+Z$ ]]; }
if [ -f "$root/$SNAP/PROVENANCE.tsv" ]; then
  now="$(date -u +%s)"
  while IFS=$'\037' read -r pn ps pc pt psha; do
    [ "$pn" = snapshot ] && continue
    pe() { echo "FAIL SNAPSHOT_AUTHENTICITY '$pn': $1"; fail=1; }
    case "$pn" in ""|*/*|*..*) pe "name must be a plain file name (no '/' or '..')"; continue;; esac
    [ -f "$root/$SNAP/$pn" ] || { pe "snapshot file missing"; continue; }
    if iso_ok "$pc" && iso_ok "$pt"; then
      cs="$(date -u -d "$pc" +%s)"; ts="$(date -u -d "$pt" +%s)"
      [ "$cs" -le "$now" ] && [ "$ts" -le "$now" ] || pe "captured_at/snapshotted_at is in the future"
      [ "$cs" -le "$ts" ] || pe "captured_at is after snapshotted_at"
    else pe "captured_at/snapshotted_at is not an ISO UTC timestamp"; fi
    case "$ps" in
      gone:*) [ -n "${ps#gone:}" ] || pe "'gone:' needs a reason";;
      ""|/*|*..*) pe "source_path '$ps' empty, absolute or contains '..'";;
      *) if [ -f "$root/$ps" ]; then
           [ "$(sha256sum "$root/$ps" | cut -d' ' -f1)" = "$(sha256sum "$root/$SNAP/$pn" | cut -d' ' -f1)" ] || echo "WARN STALE_SNAPSHOT '$pn': source $ps has changed since the snapshot (point-in-time copy)"
         else pe "source_path '$ps' does not exist (record 'gone:<reason>' if it was removed)"; fi;;
    esac
  done < <(awk -F'\t' 'BEGIN{OFS="\037"} {print $1,$2,$3,$4,$5}' "$root/$SNAP/PROVENANCE.tsv")
fi
hdrline="$(head -1 "$led" | tr -d '\r')"; hdrexp="$(echo "$COLS" | tr ' ' '\t')"
if [ "$hdrline" != "$hdrexp" ]; then echo "FAIL COLUMN_COUNT header is '$(printf '%s' "$hdrline" | tr '\t' ' ')', expected exactly '$COLS' (tab separated, no extra column)"; fail=1; fi
# frozen-evidence helpers
snapdir="$root/$SNAP"
prov_sha() { awk -F'\t' -v n="$1" 'NR>1 && $1==n {print $5}' "$snapdir/PROVENANCE.tsv" 2>/dev/null | head -1; }
echo "$COLS" | tr ' ' '\t' > "$newled"
while IFS=$'\037' read -r kind lineno id cap btype sev st layer src ev sha prod lv notes; do
  [ "$kind" = HDR ] && continue
  if [ "$kind" = BADCOUNT ]; then echo "FAIL COLUMN_COUNT line $lineno has $id columns, expected 12"; fail=1; continue; fi
  rows=$((rows+1)); who="${id:-line $lineno}"
  if [ -n "$id" ] && ! printf '%s' "$id" | LC_ALL=C grep -qE '^[A-Z]+-[0-9]+$'; then echo "FAIL $who BAD_ID id '$id' must match [A-Z]+-[0-9]+ (no invisible or lookalike characters)"; fail=1; fi
  case " $seen " in *" $id "*) [ -n "$id" ] && { echo "FAIL $who DUPLICATE_ID '$id' appears more than once"; fail=1; };; esac
  seen="$seen $id"
  i=0
  for cell in "$id" "$cap" "$btype" "$sev" "$st" "$layer" "$src" "$ev" "$sha" "$prod" "$lv" "$notes"; do
    i=$((i+1)); name="$(echo "$COLS" | cut -d' ' -f$i)"
    if [ -z "$cell" ] && { [ "$name" != evidence_sha256 ] || [ "$mode" = check ]; }; then
      echo "FAIL $who BLANK_CELL column '$name' (line $lineno) is empty"; fail=1
    fi
  done
  case "$st" in BUILT|VERIFIED|PARTIAL|NOT_IMPLEMENTED|BLOCKED) ;; *) echo "FAIL $who bad claim_status '$st'"; fail=1;; esac
  sf="${src%:*}"; sl="${src##*:}"
  srcbad=0
  case "/$sf/" in //*|*/../*) echo "FAIL $who SOURCE_ESCAPE source file '$sf' is absolute or has a '..' component"; fail=1; srcbad=1;; esac
  if [ $srcbad = 0 ] && [ -e "$root/$sf" ]; then
    case "$(realpath -m "$root/$sf")/" in "$(realpath -m "$root")"/*) ;; *) echo "FAIL $who SOURCE_ESCAPE source '$sf' resolves outside the root"; fail=1; srcbad=1;; esac
  fi
  if [ $srcbad = 0 ]; then
    if [ ! -f "$root/$sf" ] || ! [[ "$sl" =~ ^[0-9]+$ ]] || [ "$sl" -lt 1 ] || [ "$sl" -gt "$(wc -l < "$root/$sf")" ]; then echo "FAIL $who source '$src' is not an existing file:line (line must be 1..last)"; fail=1; fi
  fi
  if ! [[ "$lv" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]] || ! date -u -d "$lv" +%F 2>/dev/null | grep -qx "$lv" || [[ "$lv" > "$(date -u +%F)" ]]; then echo "FAIL $who BAD_DATE last_verified '$lv' is not a real YYYY-MM-DD date not in the future"; fail=1; fi
  newsha="none"
  if [ -n "$ev" ] && [ "$ev" != none ]; then
    pathbad=0
    case "$ev" in /*|*..*) echo "FAIL $who PATH_ESCAPE evidence_path '$ev' is absolute or contains '..'"; fail=1; pathbad=1;; esac
    if [ $pathbad = 0 ]; then
      rr="$(realpath -m "$root")"
      if [ -L "$root/$ev" ] || [ "$(realpath -m "$root/$ev")" != "$rr/$ev" ]; then echo "FAIL $who SYMLINK_EVIDENCE '$ev' is (or passes through) a symlink"; fail=1; pathbad=1; fi
    fi
    if [ $pathbad = 1 ]; then newsha="MISSING"
    elif [ -s "$root/$ev" ]; then
      newsha="$(sha256sum "$root/$ev" | awk '{print $1}')"; withev=$((withev+1))
      case "$ev" in
        "$SNAP"/*)
          b="${ev#"$SNAP"/}"; ps="$(prov_sha "$b")"
          if [ $isgit = 1 ]; then
            for sfile in "$SNAP/$b" "$SNAP/PROVENANCE.tsv"; do
              if ! git --literal-pathspecs -C "$root" ls-files --error-unmatch -- "$sfile" >/dev/null 2>&1; then echo "FAIL $who SNAPSHOT_UNTRACKED '$sfile' is not git-tracked; frozen evidence must be committed"; fail=1
              elif ! git --literal-pathspecs -C "$root" diff --quiet HEAD -- "$sfile" 2>/dev/null || [ -n "$(hidden_flag "$sfile")" ]; then echo "FAIL $who SNAPSHOT_MODIFIED '$sfile' is tracked but modified (working tree, staged, or hidden by assume-unchanged/skip-worktree)"; fail=1; fi
            done
          fi
          if [ -z "$ps" ]; then echo "FAIL $who SNAPSHOT_PROVENANCE '$b' has no row in $SNAP/PROVENANCE.tsv"; fail=1
          elif [ "$ps" != "$newsha" ]; then echo "FAIL $who SNAPSHOT_PROVENANCE '$b' sha differs from PROVENANCE.tsv (snapshot altered)"; fail=1; fi;;
        *) if [ $isgit = 0 ]; then
             echo "FAIL $who NOT_GIT '$ev' cannot be proven frozen: root is not a git repository and the path is not a snapshot"; fail=1
           else
             if ! git --literal-pathspecs -C "$root" ls-files --error-unmatch -- "$ev" >/dev/null 2>&1; then
               echo "FAIL $who VOLATILE_EVIDENCE '$ev' is untracked; snapshot it under $SNAP/ and cite the snapshot"; fail=1
             elif ! git --literal-pathspecs -C "$root" diff --quiet HEAD -- "$ev" 2>/dev/null || [ -n "$(hidden_flag "$ev")" ]; then
               echo "FAIL $who VOLATILE_EVIDENCE '$ev' is tracked but modified (working tree, staged, or hidden by assume-unchanged/skip-worktree); cite a frozen snapshot"; fail=1
             fi
           fi;;
      esac
      printf '# %s producer: %s\n%s\t%s\t%s\t%s\n' "$id" "$prod" "$id" "$layer" "$ev" "$newsha" >> "$newman"
    else echo "FAIL $who evidence_path '$ev' missing or empty"; fail=1; newsha="MISSING"; fi
  else
    case "$st" in VERIFIED|PARTIAL|BLOCKED) echo "FAIL $who status $st requires an evidence file (found 'none')"; fail=1;; esac
  fi
  if [ "$mode" = check ] && [ "$sha" != "$newsha" ]; then echo "FAIL $who ledger sha '$sha' != real '$newsha' (stale or tampered)"; fail=1; fi
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$id" "$cap" "$btype" "$sev" "$st" "$layer" "$src" "$ev" "$newsha" "$prod" "$lv" "$notes" >> "$newled"
done < "$parsed"
# vacuous-pass guards
if [ "$rows" -eq 0 ]; then echo "FAIL VACUOUS ledger has zero rows"; fail=1; fi
if [ "$rows" -gt 0 ] && [ "$withev" -eq 0 ]; then echo "FAIL VACUOUS no ledger row carries evidence (with_evidence=0)"; fail=1; fi
if [ "$mode" = check ]; then
  mrows=0; [ -f "$man" ] && mrows="$(grep -vc -e '^#' -e '^[[:space:]]*$' "$man")"
  if [ "$withev" -gt 0 ] && [ "$mrows" -eq 0 ]; then echo "FAIL VACUOUS manifest has zero data rows while the ledger has $withev evidence rows"; fail=1; fi
  if [ ! -f "$man" ] || ! cmp -s "$man" "$newman"; then echo "FAIL manifest $man differs from what the ledger implies"; fail=1; fi
  [ $fail = 0 ] && echo "ledger/manifest consistent: rows=$rows with_evidence=$withev" || echo "ledger/manifest INCONSISTENT"
  exit $fail
fi
[ $fail = 0 ] || { echo "not writing: fix the FAIL lines above"; exit 1; }
mkdir -p "$(dirname "$man")"; cp "$newman" "$man"; cp "$newled" "$led"
echo "wrote $man and updated ledger sha column: rows=$rows with_evidence=$withev"
